package org.sliceworkz.eventstore.benchmark.corpus;

import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;

/**
 * Turns a {@link CorpusSpec} into the table prefix its data lives under, so that a corpus is
 * addressed by what it contains rather than by a name somebody chose.
 *
 * <p>The point is reuse without ambiguity. Two runs asking for the same corpus land on the same
 * prefix and the second finds it already there; a run asking for anything different lands somewhere
 * else and cannot accidentally measure the wrong data. Naming corpora by hand would make "is the
 * store in the database actually the one this profile asked for?" a question of discipline.
 *
 * <p><b>The prefix has a hard budget.</b> The backend validates it as {@code [a-zA-Z0-9_]+_} and caps
 * it at 32 characters, because PostgreSQL truncates identifiers at 63 bytes and the longest index
 * name the schema generates has to stay under that. {@code bm_} plus twelve base-36 characters plus
 * the trailing underscore is 16 -- half the budget, which leaves room for the generator to derive
 * neighbour prefixes from it without overflowing.
 */
public final class CorpusFingerprint {

	/** Prefixes the suite creates all start here, so a stray corpus is recognisable in a database. */
	public static final String PREFIX_NAMESPACE = "bm_";

	/**
	 * Base-36 characters of digest kept. Twelve gives about 62 bits, which for the handful of corpora
	 * a database ever holds makes a collision far less likely than a mistake anywhere else here.
	 */
	private static final int DIGEST_CHARS = 12;

	/**
	 * Bumped by hand when the generator's output changes for an unchanged spec.
	 *
	 * <p>Without this a reusable corpus quietly means "generated by whatever version of the code
	 * happened to run first", and a change to payload shaping or tag distribution would be invisible:
	 * the fingerprint would match, the corpus would be reused, and the numbers would silently be about
	 * the old data. Changing this invalidates every corpus in every database, which is the intended
	 * cost of changing what a corpus contains.
	 */
	public static final int GENERATOR_VERSION = 3;   // 3: markers inventory-only; 2: knownEventId not fabricated

	private CorpusFingerprint ( ) { }

	/** The fingerprint of a spec: twelve lowercase base-36 characters. */
	public static String of ( CorpusSpec spec ) {
		String canonical = "gen%d|%s".formatted(GENERATOR_VERSION, spec.canonicalForm());
		byte[] digest = sha256(canonical);

		// unsigned, so the value cannot come out negative and lose a character to a minus sign
		String base36 = new BigInteger(1, digest).toString(36);
		if ( base36.length() >= DIGEST_CHARS ) {
			return base36.substring(0, DIGEST_CHARS);
		}
		return "0".repeat(DIGEST_CHARS - base36.length()) + base36;
	}

	/** The table prefix a spec's data lives under, e.g. {@code bm_3f9a12c4b70e_}. */
	public static String prefixFor ( CorpusSpec spec ) {
		return PREFIX_NAMESPACE + of(spec) + "_";
	}

	/**
	 * The prefix of the n-th neighbour store belonging to a corpus.
	 *
	 * <p>Neighbours are other <em>tables</em> in the same database, which is what the
	 * {@code MULTI_STORE} composition means. Deriving their prefixes from the owning corpus keeps them
	 * addressed by the same fingerprint, so they are provisioned, found and dropped with it rather
	 * than accumulating as orphans nobody can attribute.
	 */
	public static String neighbourPrefixFor ( CorpusSpec spec, int index ) {
		if ( index < 0 || index >= spec.neighbourVolumes().size() ) {
			throw new IndexOutOfBoundsException(
					"neighbour %d of a corpus with %d neighbours".formatted(index, spec.neighbourVolumes().size()));
		}
		// "bm_" + 12 + "_n" + at most 2 digits + "_" = at most 20 characters, inside the 32 cap
		return PREFIX_NAMESPACE + of(spec) + "_n" + index + "_";
	}

	/** Whether a prefix looks like one this suite created. */
	public static boolean isBenchmarkPrefix ( String prefix ) {
		return prefix != null && prefix.startsWith(PREFIX_NAMESPACE);
	}

	private static byte[] sha256 ( String value ) {
		try {
			return MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8));
		} catch ( NoSuchAlgorithmException e ) {
			throw new IllegalStateException("SHA-256 is required by every Java platform", e);
		}
	}
}
